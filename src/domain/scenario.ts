import { 回填旧档案 } from "./legacy";
import { 合并批次 } from "./offline";
import { 档案仓库 } from "./repository";
import { 建基线, P } from "./seed";
import { 模拟远端, 同步引擎 } from "./sync";
import type { 断网批次 } from "./types";

export interface 推演步骤 {
  阶段: string;
  标题: string;
  明细: string[];
}

export interface 推演结果 {
  步骤: 推演步骤[];
  本地: 档案仓库;
  远端: 模拟远端;
}

const T = (日: string, 时分: string) => `2026-10-${日}T${时分}:00+08:00`;

/**
 * 全流程推演：
 * 夜里断网两台平板按探方批次记录 → 回驻地合并 → 迟到边界调整 →
 * 两份读法冲突待裁定 → 装箱排队 → 同步失败按明细重试（重放不增移交记录）→ 旧档案回填
 */
export function 运行推演(): 推演结果 {
  const 步骤: 推演步骤[] = [];
  const log = (阶段: string, 标题: string, 明细: string[]) => 步骤.push({ 阶段, 标题, 明细 });

  // ---------- 第一批：平板A，T0203，10月5日夜 ----------
  const 批次甲: 断网批次 = {
    id: "BAT-A-T0203-1005",
    遗址id: "S10",
    探方id: "T0203",
    发掘日: "2026-10-05",
    平板id: "平板A",
    建批时间: T("05", "23:50"),
    操作: [
      { opId: "a1", 批次id: "BAT-A-T0203-1005", 平板id: "平板A", 时间: T("05", "20:12"), 类型: "录入出土物",
        载荷: { id: "A01", 遗址id: "S10", 探方id: "T0203", 坐标: P(2, 2), 地层id: "L3", 重量: 0.8, 名称: "陶片", 发掘日: "2026-10-05" } },
      { opId: "a2", 批次id: "BAT-A-T0203-1005", 平板id: "平板A", 时间: T("05", "20:40"), 类型: "录入出土物",
        载荷: { id: "A02", 遗址id: "S10", 探方id: "T0203", 坐标: P(2, 5), 地层id: "L2", 重量: 0.3, 名称: "动物骨", 发掘日: "2026-10-05" } },
      { opId: "a3", 批次id: "BAT-A-T0203-1005", 平板id: "平板A", 时间: T("05", "21:05"), 类型: "录入出土物",
        载荷: { id: "A03", 遗址id: "S10", 探方id: "T0203", 坐标: P(5, 1), 地层id: "L3", 重量: 1.5, 名称: "石斧", 发掘日: "2026-10-05" } },
      { opId: "a4", 批次id: "BAT-A-T0203-1005", 平板id: "平板A", 时间: T("05", "21:30"), 类型: "装箱",
        载荷: { 暂存箱id: "B01", 出土物ids: ["A01", "A02"] } },
      { opId: "a5", 批次id: "BAT-A-T0203-1005", 平板id: "平板A", 时间: T("05", "22:00"), 类型: "封箱移交",
        载荷: { 暂存箱id: "B01", 移交人: "值班员甲", 接收人: "库房老周", 签字时间: T("05", "22:05") } },
    ],
  };

  // ---------- 第二批：平板B，同探方次日凌晨 ----------
  // A04 两边坐标/层位不同；迟到的 H12 边界扩展
  const 批次乙: 断网批次 = {
    id: "BAT-B-T0203-1006",
    遗址id: "S10",
    探方id: "T0203",
    发掘日: "2026-10-06",
    平板id: "平板B",
    建批时间: T("06", "03:10"),
    操作: [
      // 平板B 对 A04 的读法（后到，与纸上记录不一致）
      { opId: "b1", 批次id: "BAT-B-T0203-1006", 平板id: "平板B", 时间: T("06", "00:20"), 类型: "录入出土物",
        载荷: { id: "A04", 遗址id: "S10", 探方id: "T0203", 坐标: P(2.95, 3.02), 地层id: "L2", 重量: 2.2, 名称: "陶罐", 发掘日: "2026-10-06" } },
      // 先由纸上登记 A04 第一读法（时间更早，排序后先入库）
      { opId: "b0", 批次id: "BAT-B-T0203-1006", 平板id: "纸质补登", 时间: T("05", "23:40"), 类型: "录入出土物",
        载荷: { id: "A04", 遗址id: "S10", 探方id: "T0203", 坐标: P(3, 3), 地层id: "L3", 重量: 2.2, 名称: "陶罐", 发掘日: "2026-10-05" } },
      // 迟到的边界调整：H12 由 4 米见方扩到 5.5 米
      { opId: "b2", 批次id: "BAT-B-T0203-1006", 平板id: "平板B", 时间: T("06", "01:10"), 类型: "调整遗迹边界",
        载荷: { 遗迹id: "H12", 边界: [P(0, 0), P(5.5, 0), P(5.5, 5.5), P(0, 5.5)] } },
    ],
  };

  const 本地 = 建基线();
  const 远端 = new 模拟远端(建基线());

  // 第一批合并
  const r1 = 合并批次(本地, 批次甲);
  log("① 断网记录按探方批次合并", "平板A批次合并（10月5日夜）", [
    ...r1.明细.map((m) => `· ${m.类型}｜${m.说明}`),
    `B01 装箱后箱位=${本地.暂存箱.get("B01")!.箱位 ?? "—"}，总重量 ${本地.暂存箱.get("B01")!.总重量}kg（陶片0.8+骨0.3）`,
    `A01 归属 ${本地.出土物.get("A01")!.依据!.遗迹id}，A02 归属 ${本地.出土物.get("A02")!.依据!.遗迹id}（层位决定：L2 落沟 G3）`,
  ]);

  // 第二批合并：边界重算 + 冲突
  const r2 = 合并批次(本地, 批次乙);
  const A03依据 = 本地.出土物.get("A03")!.依据!;
  const A01快照 = 本地.移交记录.get("YJ-a5")!.依据快照["A01"];
  log("② 迟到边界调整，归属失效重算", "平板B批次合并：H12 边界 4m→5.5m", [
    ...r2.明细.filter((m) => m.类型 !== "录入出土物" || m.说明.includes("A04")).map((m) => `· ${m.类型}｜${m.结果}｜${m.说明}`),
    `A03（石斧，5,1）原在遗迹外 → 重算后归属 ${A03依据.遗迹id ?? "探方层位"}（边界v${A03依据.边界版本}）`,
    `A01 已签字移交：仍保留原依据 H12@v${A01快照.边界版本}，冻结=${A01快照.冻结 ? "是" : "否"}，未被重算改写`,
  ]);

  const 冲突 = [...本地.冲突.values()].find((c) => c.出土物id === "A04")!;
  log("③ 坐标/层位两边不同，留两份待领队裁定", `A04 陶罐（${冲突.差异}不一致）`, [
    `第1份（${冲突.两份[0].来源}）：坐标(${冲突.两份[0].坐标!.x},${冲突.两份[0].坐标!.y}) 层位 ${冲突.两份[0].地层id}`,
    `第2份（${冲突.两份[1].来源}）：坐标(${冲突.两份[1].坐标!.x},${冲突.两份[1].坐标!.y}) 层位 ${冲突.两份[1].地层id}`,
    `冲突期间 A04 状态=${本地.出土物.get("A04")!.状态}，禁止装箱`,
  ]);

  // 领队裁定采用第1份
  const 批次裁定: 断网批次 = {
    ...批次乙,
    id: "BAT-LEAD-1006",
    操作: [
      { opId: "c1", 批次id: "BAT-LEAD-1006", 平板id: "领队终端", 时间: T("06", "08:30"), 类型: "领队裁定",
        载荷: { 冲突id: 冲突.id, 采用序号: 0, 裁定人: "领队" } },
      { opId: "c2", 批次id: "BAT-LEAD-1006", 平板id: "领队终端", 时间: T("06", "08:45"), 类型: "装箱",
        载荷: { 暂存箱id: "B02", 出土物ids: ["A03", "A04"] } },
    ],
    建批时间: T("06", "08:45"),
  };
  const r3 = 合并批次(本地, 批次裁定);
  const B01 = 本地.暂存箱.get("B01")!;
  const B02 = 本地.暂存箱.get("B02")!;
  log("④ 领队裁定 + 箱位排队", "裁定采用第1份读法，A03/A04 装入 B02", [
    ...r3.明细.map((m) => `· ${m.类型}｜${m.说明}`),
    `A04 采用 L3 读法 → 归属 ${本地.出土物.get("A04")!.依据!.遗迹id}；若取 L2 读法则因层位不符不落 H12`,
    `箱位队列（总重量降序、件数降序）：B02 总重${B02.总重量}kg/${B02.出土物ids.length}件 箱位=${B02.箱位 ?? "—"}；B01 总重${B01.总重量}kg 已封箱出队`,
  ]);

  // ---------- 同步：远端只做批次重放；注入 B02 封箱首试响应丢失 ----------
  const 首批失败 = new Set(["d1"]);
  远端.故障注入 = (op) => {
    if (首批失败.has(op.opId)) {
      首批失败.delete(op.opId);
      return "响应丢失";
    }
    return undefined;
  };

  // B02 封箱移交（驻地补签字）
  const 批次封箱: 断网批次 = {
    id: "BAT-SYNC-1006",
    遗址id: "S10",
    探方id: "T0203",
    发掘日: "2026-10-06",
    平板id: "驻地站",
    建批时间: T("06", "09:00"),
    操作: [
      { opId: "d1", 批次id: "BAT-SYNC-1006", 平板id: "驻地站", 时间: T("06", "09:05"), 类型: "封箱移交",
        载荷: { 暂存箱id: "B02", 移交人: "值班员乙", 接收人: "库房老周", 签字时间: T("06", "09:05") } },
    ],
  };
  // 本地也封箱，保持与远端一致
  合并批次(本地, 批次封箱);

  const 引擎 = new 同步引擎(远端, 本地);
  const 待同步 = [批次甲, 批次乙, 批次裁定, 批次封箱];
  const 首试 = 引擎.同步(待同步);
  log("⑤ 同步失败，按未完成明细重试", "首批推送：B02 封箱操作首试响应丢失", [
    `首试成功 ${首试.成功.length} 个操作；未完成 ${首试.未完成.length} 条：`,
    ...首试.未完成.map((f) => `· 明细 ${f.opId}（${f.类型}）：${f.错误}；远端已生效=${f.远端已生效 ? "是" : "否"}`),
  ]);

  const 重试 = 引擎.同步(待同步, 首试.未完成);
  log("⑥ 重放不增加移交记录", "仅按未完成明细重放 d1", [
    `重试后未完成 ${重试.未完成.length} 条；网络轨迹：${远端.网络日志.filter((l) => l.opId === "d1").map((l) => l.结果).join(" → ")}`,
    `远端移交记录总数 = ${远端.库.移交记录.size}（YJ-a5、YJ-d1 各一条，重试未新增）`,
    `远端 B02 出土物 ${远端.库.移交记录.get("YJ-d1")!.出土物ids.join("/")}，签字依据全部保留`,
  ]);

  // ---------- 旧档案回填 ----------
  const 回填 = 回填旧档案(本地, [
    { 旧编号: "X-001", 遗址id: "S10", 探方编号: "T0204", 发掘日: "2026-09-28", 坐标: P(1, 1), 地层编号: "第3层", 重量: 0.6, 名称: "旧藏陶片" },
    { 旧编号: "X-002", 遗址id: "S10", 探方编号: "T0204", 坐标: P(2, 2), 地层编号: "第3层", 重量: 0.4, 名称: "日期缺失件" },
    { 旧编号: "X-003", 遗址id: "S10", 探方编号: "T0204", 发掘日: "2026-09-28", 重量: 0.9, 名称: "层位坐标缺失件" },
  ]);
  log("⑦ 旧档案无探方批次，按遗址+发掘日回填", "三条旧档案导入，缺项先待核", [
    ...回填.map((h) => `· ${h.旧编号}：批次 ${h.批次id ?? "无（缺遗址/发掘日）"}，状态=${h.状态}${h.待核项.length ? "，待核：" + h.待核项.join("、") : ""}`),
    `同遗址同发掘日 X-001/X-003 归并到同一回填批次 BAT-S10-20260928`,
  ]);

  return { 步骤, 本地, 远端 };
}
